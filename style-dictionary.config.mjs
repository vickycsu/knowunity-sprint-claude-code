import StyleDictionary from 'style-dictionary';

const formatCssValue = (token) => {
  const rawValue = token.$value ?? token.original?.$value ?? token.value;

  if (rawValue === undefined || rawValue === null) {
    return null;
  }

  if (typeof rawValue === 'string' || typeof rawValue === 'number') {
    return String(rawValue);
  }

  if (typeof rawValue === 'object') {
    if ('hex' in rawValue) {
      const { hex, alpha } = rawValue;
      if (alpha !== undefined && typeof hex === 'string') {
        const value = hex.replace('#', '');
        const normalized = value.length === 3 ? value.split('').map((char) => char + char).join('') : value;
        const r = Number.parseInt(normalized.slice(0, 2), 16);
        const g = Number.parseInt(normalized.slice(2, 4), 16);
        const b = Number.parseInt(normalized.slice(4, 6), 16);
        return `rgba(${r}, ${g}, ${b}, ${Number(alpha)})`;
      }

      return typeof rawValue.hex === 'string' ? rawValue.hex : null;
    }

    if ('value' in rawValue && 'unit' in rawValue) {
      return `${rawValue.value}${rawValue.unit}`;
    }

    if ('gradientType' in rawValue && Array.isArray(rawValue.stops)) {
      const stopColors = rawValue.stops
        .map((stop) => (stop && typeof stop === 'object' ? formatCssValue({ $value: stop.color }) : null))
        .filter((value) => value !== null);

      if (stopColors.length === 0) {
        return null;
      }

      return `${rawValue.gradientType}-gradient(${rawValue.angle}deg, ${stopColors.join(', ')})`;
    }

    if ('fontFamily' in rawValue || 'fontSize' in rawValue || 'fontWeight' in rawValue) {
      const parts = [];

      if (typeof rawValue.fontFamily === 'string') {
        parts.push(rawValue.fontFamily);
      }
      if (typeof rawValue.fontSize === 'object' && rawValue.fontSize !== null) {
        parts.push(`${rawValue.fontSize.value}${rawValue.fontSize.unit ?? ''}`);
      }
      if (typeof rawValue.lineHeight === 'object' && rawValue.lineHeight !== null) {
        parts.push(`/ ${rawValue.lineHeight.value}${rawValue.lineHeight.unit ?? ''}`);
      }
      if (typeof rawValue.fontWeight === 'string') {
        parts.push(rawValue.fontWeight);
      }

      return parts.join(' ');
    }
  }

  return null;
};

StyleDictionary.registerFormat({
  name: 'css/custom-variables',
  format: ({ dictionary }) => {
    const lines = [
      '/**',
      ' * This file is generated by the token build and must not be edited by hand.',
      ' */',
      '',
      ':root {',
    ];

    const tokens = dictionary.allTokens.filter((token) => {
      return Array.isArray(token.path) && token.path.length > 0;
    });

    for (const token of tokens) {
      const cssValue = formatCssValue(token);
      if (cssValue === null) {
        continue;
      }

      const name = `--color-${token.path.join('-')}`;
      lines.push(`  ${name}: ${cssValue};`);
    }

    lines.push('}');
    return lines.join('\n');
  },
});

export default {
  source: ['tokens/tokens.json'],
  platforms: {
    css: {
      transformGroup: 'css',
      buildPath: 'build/css/',
      files: [
        {
          destination: 'tokens.css',
          format: 'css/custom-variables',
        },
      ],
    },
  },
};
